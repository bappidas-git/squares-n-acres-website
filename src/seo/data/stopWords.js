/** Whether a single word carries no meaning of its own. */
export const isStopWord = (word) => STOP_WORDS.has(String(word ?? '').toLowerCase());

/** The words of a phrase that are not stop words, in order. */
export const withoutStopWords = (words = []) => words.filter((word) => !isStopWord(word));

