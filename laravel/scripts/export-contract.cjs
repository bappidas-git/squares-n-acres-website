#!/usr/bin/env node
/**
 * Exports the API contract from the website repository to PHP.
 *
 *   node laravel/scripts/export-contract.cjs          # from the repository root
 *
 * The Laravel API is built against the same descriptors the mock server, the
 * seed validator and the backend guidelines are generated from:
 *
 *   mock-server/schemas/models.js          → resources/contract/models.php
 *   src/services/schemas/*.js              → resources/contract/schemas.php
 *   src/config/enums.js                    → resources/contract/enums.php
 *   backend_developer_guidelines/schema.sql → resources/contract/tables.php
 *
 * Reading them rather than copying them by hand is what keeps a 422 of this
 * API and a 422 of the mock the same answer: a field added to a descriptor is
 * one `node` command away from being validated, stored and returned here.
 *
 * `tables.php` is `schema.sql` with the deviations the Laravel build makes on
 * purpose (listed in DEVIATIONS below and in laravel/README.md). The
 * migrations and the document mapper both read it, so the columns the code
 * writes are the columns the database has.
 *
 * The script ends with a coverage check: every writable field of every
 * collection must land in a column, and every column must come from a field.
 * It exits 1 when either is not true.
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..', '..');
const OUT = path.resolve(__dirname, '..', 'resources', 'contract');

const { MODELS } = require(path.join(ROOT, 'mock-server/schemas/models.js'));
const { schemas } = require(path.join(ROOT, 'src/services/schemas'));
const enums = require(path.join(ROOT, 'src/config/enums.js'));

/* ------------------------------------------------------------------ *
 * A JavaScript value as a PHP literal
 * ------------------------------------------------------------------ */

const isPlainObject = (value) =>
  typeof value === 'object' && value !== null && !Array.isArray(value) && !(value instanceof RegExp);

/** A PHP single-quoted string. */
const phpString = (text) => `'${String(text).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/**
 * Renders a value as PHP. An empty object stays an object (`(object) []`),
 * because `{}` and `[]` are different answers to the frontend — a block's
 * `data` defaults to `{}`.
 */
function php(value, depth = 0) {
  const pad = '    '.repeat(depth + 1);
  const end = '    '.repeat(depth);

  if (value === null || value === undefined) return 'null';
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : 'null';
  if (typeof value === 'string') return phpString(value);
  if (value instanceof RegExp) return phpString(value.source);

  if (Array.isArray(value)) {
    const items = value.filter((item) => typeof item !== 'function');
    if (items.length === 0) return '[]';
    return `[\n${items.map((item) => `${pad}${php(item, depth + 1)},`).join('\n')}\n${end}]`;
  }

  if (isPlainObject(value)) {
    const entries = Object.entries(value).filter(([, item]) => typeof item !== 'function');
    if (entries.length === 0) return '(object) []';
    return `[\n${entries
      .map(([key, item]) => `${pad}${phpString(key)} => ${php(item, depth + 1)},`)
      .join('\n')}\n${end}]`;
  }

  return 'null';
}

function writePhp(file, comment, value) {
  const body = `<?php\n\n/*\n * ${comment}\n *\n * Generated by laravel/scripts/export-contract.cjs — do not edit by hand.\n */\n\nreturn ${php(value)};\n`;
  fs.writeFileSync(path.join(OUT, file), body);
  console.log(`wrote resources/contract/${file}`);
}

/* ------------------------------------------------------------------ *
 * Enums: values, entries and the plain lists/maps beside them
 * ------------------------------------------------------------------ */

function exportEnums() {
  const out = {};
  for (const [name, value] of Object.entries(enums)) {
    if (typeof value === 'function') continue;
    if (isPlainObject(value) && Array.isArray(value.entries) && Array.isArray(value.values)) {
      out[name] = { values: value.values, entries: value.entries };
      continue;
    }
    out[name] = value;
  }
  return out;
}

/* ------------------------------------------------------------------ *
 * schema.sql → tables
 * ------------------------------------------------------------------ */

/** snake_case → camelCase */
const camel = (text) => text.replace(/_([a-z0-9])/g, (_match, letter) => letter.toUpperCase());

/** The document path a column comment names (`'INR · pricing.currency'` → `pricing.currency`). */
function pathFromComment(comment) {
  if (!comment) return null;
  const parts = comment.split('·').map((part) => part.trim());
  const found = parts.find((part) => /^[a-z][A-Za-z0-9]*(\.[a-z][A-Za-z0-9]*)+$/.test(part));
  return found ?? null;
}

/** The storage kind of an SQL type. */
function kindOf(sqlType) {
  const type = sqlType.toUpperCase();
  if (type === 'TINYINT(1)') return 'bool';
  if (/^(BIG)?INT|^TINYINT/.test(type)) return 'int';
  if (type.startsWith('DECIMAL')) return 'number';
  if (type === 'DATE') return 'date';
  if (type.startsWith('DATETIME')) return 'datetime';
  if (type === 'JSON') return 'json';
  return 'string';
}

function parseSchemaSql(sql) {
  const tables = {};
  const blockRe = /-- collection: ([^\n]+)\nCREATE TABLE `([a-z_]+)` \(\n([\s\S]*?)\n\) ENGINE/g;
  let match;

  while ((match = blockRe.exec(sql)) !== null) {
    const [, heading, name, body] = match;
    const table = {
      name,
      collection: heading.split(' ')[0],
      kind: 'table',
      field: null,
      columns: [],
      primary: [],
      unique: [],
      indexes: [],
      fullText: [],
      foreignKeys: [],
    };

    // `properties — rows of properties.images`, `properties — properties.amenityIds`
    const child = /— rows of [a-zA-Z]+\.([a-zA-Z]+)/.exec(heading);
    const pivot = /— [a-zA-Z]+\.([a-zA-Z]+)$/.exec(heading);
    if (child) {
      table.kind = 'child';
      table.field = child[1];
    } else if (pivot) {
      table.kind = 'pivot';
      table.field = pivot[1];
    } else if (heading.includes('Laravel Sanctum')) {
      table.kind = 'sanctum';
    }

    for (const rawLine of body.split('\n')) {
      const line = rawLine.trim().replace(/,$/, '');
      let m;
      if ((m = /^`([a-z_]+)` ([A-Z]+(?:\(\d+(?:,\d+)?\))?(?: UNSIGNED)?)(.*)$/.exec(line))) {
        const [, column, type, rest] = m;
        const comment = /COMMENT '((?:[^'\\]|\\.)*)'/.exec(rest)?.[1] ?? null;
        const defaultMatch = /DEFAULT ('(?:[^'\\]|\\.)*'|[^\s]+)/.exec(rest);
        let defaultValue;
        let hasDefault = false;
        if (defaultMatch) {
          hasDefault = true;
          const raw = defaultMatch[1];
          if (raw === 'NULL') defaultValue = null;
          else if (raw.startsWith("'")) defaultValue = raw.slice(1, -1);
          else defaultValue = Number(raw);
        }
        table.columns.push({
          name: column,
          type,
          kind: kindOf(type),
          nullable: !/NOT NULL/.test(rest),
          hasDefault,
          default: hasDefault ? defaultValue : null,
          autoIncrement: /AUTO_INCREMENT/.test(rest),
          comment,
        });
      } else if ((m = /^PRIMARY KEY \((.+)\)$/.exec(line))) {
        table.primary = m[1].split(',').map((c) => c.trim().replace(/`/g, ''));
      } else if ((m = /^UNIQUE KEY `([a-z_]+)` \((.+)\)$/.exec(line))) {
        table.unique.push({ name: m[1], columns: m[2].split(',').map((c) => c.trim().replace(/`/g, '')) });
      } else if ((m = /^FULLTEXT KEY `([a-z_]+)` \((.+)\)$/.exec(line))) {
        table.fullText.push({ name: m[1], columns: m[2].split(',').map((c) => c.trim().replace(/`/g, '')) });
      } else if ((m = /^KEY `([a-z_]+)` \((.+)\)$/.exec(line))) {
        table.indexes.push({ name: m[1], columns: m[2].split(',').map((c) => c.trim().replace(/`/g, '')) });
      } else if (
        (m = /^CONSTRAINT `([a-z_]+)` FOREIGN KEY \(`([a-z_]+)`\) REFERENCES `([a-z_]+)` \(`([a-z_]+)`\) ON DELETE (RESTRICT|CASCADE|SET NULL)$/.exec(
          line
        ))
      ) {
        table.foreignKeys.push({
          name: m[1],
          column: m[2],
          references: m[4],
          on: m[3],
          onDelete: m[5].toLowerCase(),
        });
      } else if (line !== '') {
        throw new Error(`schema.sql: cannot read line of ${name}: ${line}`);
      }
    }

    tables[name] = table;
  }

  return tables;
}

/**
 * What the Laravel build changes in `schema.sql`, and why. Each is listed in
 * laravel/README.md → "Deviations from schema.sql".
 */
const DEVIATIONS = [
  'every DATETIME is DATETIME(3): the API reports milliseconds, and the stale-save guard compares the exact `updatedAt` a form read',
  'articles.author_id: ON DELETE RESTRICT (was SET NULL on a NOT NULL column, which MySQL 8 refuses: error 1830); an author in use is refused by the API first',
  'property_views.property_id: ON DELETE CASCADE (was SET NULL on a NOT NULL column, error 1830)',
  'child tables gain `local_id` (the id the item has inside its parent document, which the API returns and addresses) and `position` (the item\'s place in the array)',
  'property_amenity and property_badge gain `position`: the order the editor chose, as property_similar and article_tag already keep',
  'personal_access_tokens is Sanctum\'s own table (its migration), not the mock\'s token store',
];

function applyDeviations(tables) {
  for (const table of Object.values(tables)) {
    for (const column of table.columns) {
      if (column.kind === 'datetime') column.type = 'DATETIME(3)';
    }

    for (const fk of table.foreignKeys) {
      const column = table.columns.find((entry) => entry.name === fk.column);
      if (fk.onDelete === 'set null' && column && !column.nullable) {
        fk.onDelete = table.name === 'property_views' ? 'cascade' : 'restrict';
      }
    }

    if (table.kind === 'child') {
      const at = table.columns.findIndex((column) => column.name.endsWith('_id') && column.name !== 'id');
      table.columns.splice(at + 1, 0, {
        name: 'local_id',
        type: 'INT UNSIGNED',
        kind: 'int',
        nullable: false,
        hasDefault: true,
        default: 0,
        autoIncrement: false,
        comment: 'the item id inside its parent document',
      });
      table.columns.splice(at + 2, 0, {
        name: 'position',
        type: 'INT',
        kind: 'int',
        nullable: false,
        hasDefault: true,
        default: 0,
        autoIncrement: false,
        comment: 'the item position inside the parent array',
      });
    }

    if (table.kind === 'pivot' && !table.columns.some((column) => column.name === 'position')) {
      table.columns.push({
        name: 'position',
        type: 'INT',
        kind: 'int',
        nullable: false,
        hasDefault: true,
        default: 0,
        autoIncrement: false,
        comment: 'the order the admin chose',
      });
    }
  }
  return tables;
}

/* ------------------------------------------------------------------ *
 * Column ↔ document path
 * ------------------------------------------------------------------ */

/** Columns the store manages itself rather than mapping from a field. */
const STRUCTURAL = new Set(['id', 'deleted_at', 'local_id', 'position']);

/** Descriptor of a dotted path inside a `fields` map. */
function descriptorAt(fields, dotted) {
  let shape = fields;
  let descriptor = null;
  for (const key of dotted.split('.')) {
    descriptor = shape?.[key] ?? null;
    if (!descriptor) return null;
    shape = descriptor.shape ?? null;
  }
  return descriptor;
}

function assignPaths(tables) {
  const problems = [];

  for (const table of Object.values(tables)) {
    if (table.kind === 'sanctum') continue;
    const model = MODELS[table.collection];
    if (!model) {
      problems.push(`${table.name}: no model for collection ${table.collection}`);
      continue;
    }

    let fields = model.fields;
    if (table.kind === 'child') fields = model.fields[table.field]?.items?.shape ?? {};

    for (const column of table.columns) {
      if (STRUCTURAL.has(column.name)) continue;
      if (table.kind === 'child' && column.name === `${singular(table.collection)}_id`) {
        column.role = 'parent';
        continue;
      }
      if (table.kind === 'pivot') {
        column.role = column.name === `${singular(table.collection)}_id` ? 'parent' : 'related';
        continue;
      }
      if (table.kind === 'child' && table.field === 'unitConfigurations' && column.name === 'order') {
        // "position inside the parent array": the item has no `order` of its own.
        column.role = 'position-alias';
        continue;
      }
      if (column.name === 'password' && table.name === 'admin_users') {
        column.path = 'password';
        column.role = 'secret';
        continue;
      }

      const dotted = pathFromComment(column.comment) ?? camel(column.name);
      const descriptor = descriptorAt(fields, dotted);
      if (!descriptor && ['created_at', 'updated_at'].includes(column.name)) {
        // The row's own bookkeeping — a child row, a singleton's first save —
        // which no field of the document carries: the store stamps it.
        column.role = 'timestamp';
        continue;
      }
      column.path = dotted;
      if (!descriptor) {
        problems.push(`${table.name}.${column.name}: no field ${dotted} in ${table.collection}`);
        continue;
      }
      column.docType = descriptor.type ?? null;
      if (descriptor.type === 'enum' && (descriptor.enum ?? []).every((value) => typeof value === 'number')) {
        column.docType = 'int';
      }
    }
  }

  // Every writable field reaches a column (or a child table / pivot).
  for (const [collection, model] of Object.entries(MODELS)) {
    if (collection === 'apiTokens') continue;
    const own = Object.values(tables).filter((table) => table.collection === collection);
    const columnPaths = new Set(own.flatMap((table) => table.kind === 'table' ? table.columns.map((c) => c.path).filter(Boolean) : []));
    const arrayFields = new Set(own.filter((table) => table.kind !== 'table').map((table) => table.field));

    const walk = (shape, prefix) => {
      for (const [field, descriptor] of Object.entries(shape)) {
        const dotted = prefix ? `${prefix}.${field}` : field;
        if (descriptor.read) continue;
        if (!prefix && ['id', 'createdAt', 'updatedAt'].includes(field)) continue;
        if (!prefix && arrayFields.has(field)) continue;
        if (columnPaths.has(dotted)) continue;
        if (descriptor.type === 'object' && descriptor.shape && !columnPaths.has(dotted)) {
          walk(descriptor.shape, dotted);
          continue;
        }
        problems.push(`${collection}: field ${dotted} has no column`);
      }
    };
    walk(model.fields, '');
  }

  return problems;
}

/** `properties` → `property`, `leads` → `lead`, `pages` → `page`, `articles` → `article`. */
function singular(collection) {
  return { properties: 'property', leads: 'lead', articles: 'article', pages: 'page' }[collection] ?? collection;
}

/* ------------------------------------------------------------------ *
 * Main
 * ------------------------------------------------------------------ */

function main() {
  fs.mkdirSync(OUT, { recursive: true });

  const sql = fs.readFileSync(path.join(ROOT, 'backend_developer_guidelines/schema.sql'), 'utf8');
  const generatedFrom = /generatedFrom: ([0-9a-f]+)/.exec(sql)?.[1] ?? 'unknown';
  const tables = applyDeviations(parseSchemaSql(sql));
  const problems = assignPaths(tables);

  writePhp('models.php', `Collection descriptors — mock-server/schemas/models.js (contract ${generatedFrom}).`, MODELS);
  writePhp('schemas.php', `Request-body schemas — src/services/schemas (contract ${generatedFrom}).`, schemas);
  writePhp('enums.php', `Enums — src/config/enums.js (contract ${generatedFrom}).`, exportEnums());
  writePhp(
    'tables.php',
    `Tables — backend_developer_guidelines/schema.sql (contract ${generatedFrom}), with the deviations:\n *   - ${DEVIATIONS.join('\n *   - ')}`,
    tables
  );

  if (problems.length > 0) {
    console.error(`\n${problems.length} mapping problem(s):\n  ${problems.join('\n  ')}`);
    process.exitCode = 1;
  } else {
    console.log('\nevery writable field has a column, and every column a field');
  }
}

if (require.main === module) main();

module.exports = { parseSchemaSql, applyDeviations, assignPaths, php, DEVIATIONS };
